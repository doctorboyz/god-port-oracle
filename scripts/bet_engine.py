#!/usr/bin/env python3
"""True-bet live engine — 9 contract cells, brokerless paper bets.

One container (oracle-engine-farmbet), one DB (/app/data/bet.db), 9 cells
(BET-{A|B|C}{6|10|8}) seeded $1,000 each. Every cycle (default 60s):

1. read the shared paper feed (M5 closed bars — the fetcher guarantees
   only closed bars are ever written);
2. resolve each cell's open bet, preferring TICKS (bridge copy_ticks_from,
   flags=1 INFO — ordered, so never ambiguous) with the bar-conservative
   walk as fallback when ticks are unavailable (halt/fetch failure);
3. open a new bet when the cell is flat and the last CLOSED bar signals —
   fill at the current mid, contract levels fixed from that entry price,
   then held to the end (no trailing/time-stop/hour gate/circuit breaker).

Broker-safety contract (mirrors scripts/paper_feed_fetcher.py): the ONLY
bridge methods touched are initialize / symbol_select / symbol_info /
copy_ticks_from / symbol_info_tick — read-only market data. No order, no
position, no shutdown.

Environment (generated by paper_farm_apply.py from farm_variants.yml):
    DB_PATH             SQLite path (default /app/data/bet.db)
    DATA_DIR            feed dir (default /app/feed)
    ACCOUNTS            comma-separated cell ids (BET-A6,...)
    BET_POLL_INTERVAL   cycle seconds (default 60)
    BET_BRIDGE_HOST/PORT  tick source (VPS mt5q bridge over Tailscale)
    BET_MAX_CANDLE_AGE_SECONDS  stale-feed entry guard (default 1800)
    Per-cell: BET_FAMILY_<cell>, BET_TP_DIST_<cell>, BET_SL_DIST_<cell>,
              BET_BOLL_THRESHOLD_<cell>, INITIAL_BALANCE_<cell>,
              BET_RISK_FRACTION_<cell>, BET_SPREAD_COST_PER_OZ_<cell>
"""

from __future__ import annotations

import logging
import os
import sqlite3
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

import pandas as pd

# Repo-root bootstrap when invoked as `python3 scripts/bet_engine.py`
_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from broky.bet import entries, store  # noqa: E402
from broky.bet.contract import (  # noqa: E402
    BetGeometry, OpenBet, open_bet, OUTCOME_TP, OUTCOME_SL,
)
from broky.bet.engine import CellSpec  # noqa: E402

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(name)s: %(message)s",
)
logger = logging.getLogger("bet_engine")

DB_PATH = Path(os.environ.get("DB_PATH", "/app/data/bet.db"))
FEED_DIR = Path(os.environ.get("DATA_DIR", "/app/feed"))
ACCOUNTS = [a.strip() for a in os.environ.get("ACCOUNTS", "").split(",") if a.strip()]
POLL_INTERVAL = int(os.environ.get("BET_POLL_INTERVAL", "60"))
BRIDGE_HOST = os.environ.get("BET_BRIDGE_HOST", "vpsdeluna")
BRIDGE_PORT = int(os.environ.get("BET_BRIDGE_PORT", "5012"))
MAX_CANDLE_AGE = int(os.environ.get("BET_MAX_CANDLE_AGE_SECONDS", "1800"))
# copy_ticks_from flags: 1 = COPY_TICKS_INFO (bid/ask) — flags=2 (ALL)
# returns [] on this Exness feed (T0 probe 2026-11-11).
TICK_FLAGS_INFO = 1
# Hard cap per fetch: ~4.3 ticks/s live → 200k ticks covers any open bet's
# backlog window without a giant rpyc payload.
TICK_FETCH_CAP = 200_000


def load_m5() -> Optional[pd.DataFrame]:
    """Closed M5 bars from the shared feed CSV (fetcher writes closed only)."""
    path = FEED_DIR / "XAUUSD_M5.csv"
    if not path.exists():
        logger.warning("feed missing: %s", path)
        return None
    try:
        df = pd.read_csv(
            path, header=None,
            names=["date", "open", "high", "low", "close", "volume"],
            parse_dates=["date"],
        ).set_index("date")
    except Exception as exc:
        logger.error("feed read failed: %s", exc)
        return None
    if df.empty:
        return None
    return df.dropna().sort_index()


class TickFeed:
    """Persistent READ-ONLY bridge client for ticks + current mid.

    Same safety posture as the fetcher's BridgeFeed: one persistent rpyc
    connection, heal with initialize() on empty reads, NEVER call the
    server-side shutdown (mt5q also serves the fetcher).
    """

    def __init__(self, host: str = BRIDGE_HOST, port: int = BRIDGE_PORT,
                 symbol: str = "XAUUSD") -> None:
        self.host, self.port, self.symbol = host, port, symbol
        self._resolved: Optional[str] = None
        self._conn = None

    def _close(self) -> None:
        if self._conn is not None:
            try:
                self._conn.close()
            except Exception:
                pass
        self._conn = None
        self._resolved = None

    def _connect(self) -> bool:
        if self._conn is not None:
            return True
        import rpyc  # deferred: tests mock this class entirely

        try:
            self._conn = rpyc.connect(
                self.host, self.port, config={"sync_request_timeout": 60},
            )
            if not self._conn.root.initialize():
                logger.warning("bridge initialize failed at %s:%s", self.host, self.port)
                self._close()
                return False
            self._resolved = self._resolve_symbol()
            logger.info("bridge connected %s:%s symbol=%s",
                        self.host, self.port, self._resolved)
            return True
        except Exception as exc:
            logger.warning("bridge connect %s:%s failed: %s", self.host, self.port, exc)
            self._close()
            return False

    def _resolve_symbol(self) -> str:
        from metty.bridge.client import SYMBOL_ALIASES

        for name in SYMBOL_ALIASES.get(self.symbol, [self.symbol]):
            try:
                self._conn.root.symbol_select(name, True)
                if self._conn.root.symbol_info(name):
                    return name
            except Exception:
                continue
        return self.symbol

    def mid(self) -> Optional[float]:
        """Current (bid+ask)/2 — the entry price source for new bets."""
        try:
            if not self._connect():
                return None
            info = self._conn.root.symbol_info_tick(self._resolved)
            if not info:
                return None
            bid, ask = float(info["bid"]), float(info["ask"])
            if bid <= 0 or ask <= 0:
                return None
            return (bid + ask) / 2.0
        except Exception as exc:
            logger.warning("mid fetch failed: %s", exc)
            self._close()
            return None

    def ticks_since(self, from_epoch: int) -> Optional[list[dict]]:
        """INFO ticks from `from_epoch` to now, or None on failure.

        Bulk materialization (live incident 2026-11-11 15:33-15:47 UTC):
        rpyc returns each tick as a dict NETREF — every field access is a
        ~50ms round trip to the VPS, so `list(remote)` + per-field reads
        burned 136s for a single 10-minute fetch (and `tick.get()` is
        blocked by the server's rpyc config entirely → the first live
        resolution crashed on tick #1). Calling str() on the whole remote
        list costs ONE round trip (server renders the entire list to its
        repr, ~240KB for 10 minutes of ticks) which ast.literal_eval parses
        locally — 0.3s end-to-end for the same data.
        """
        import ast

        try:
            if not self._connect():
                return None
            ticks = self._conn.root.copy_ticks_from(
                self._resolved, int(from_epoch), TICK_FETCH_CAP, TICK_FLAGS_INFO,
            )
            if not ticks:
                return []
            return ast.literal_eval(str(ticks))
        except Exception as exc:
            logger.warning("tick fetch failed: %s", exc)
            self._close()
            return None


def cell_spec_from_env(cell_id: str) -> CellSpec:
    """Per-cell knobs arrive as `<KNOB>_<CELL>` env lines (compose emits them).

    The env KEY is dash-sanitized (BET-A6 → BET_A6): container runtimes drop
    env entries with '-' in the key from the PID-1 environment (live proof
    2026-11-11 — the boot seed silently wrote defaults for every cell). The
    cell_id itself keeps its task-required form (BET-A6) in DB/reports.

    Per-cell knobs are read as LITERAL f-string templates (BET_FAMILY_{cell}
    etc.) so static coverage guards see the pipe end-to-end — building the
    knob name from a variable hid it from the ISSUE-100 scan.
    """
    safe = cell_id.replace("-", "_")
    return CellSpec(
        cell_id=cell_id,
        family=os.environ.get(f"BET_FAMILY_{safe}", "A").strip().upper(),
        geometry=BetGeometry(
            tp_dist=float(os.environ.get(f"BET_TP_DIST_{safe}", "6.0")),
            sl_dist=float(os.environ.get(f"BET_SL_DIST_{safe}", "12.0")),
        ),
        seed_balance=float(os.environ.get(f"INITIAL_BALANCE_{safe}", "1000")),
        risk_fraction=float(os.environ.get(f"BET_RISK_FRACTION_{safe}", "0.015")),
        boll_threshold=float(os.environ.get(f"BET_BOLL_THRESHOLD_{safe}", "0.85")),
        spread_cost_per_oz=float(
            os.environ.get(f"BET_SPREAD_COST_PER_OZ_{safe}", "0.20")
        ),
    )


def seed_all_cells(conn: sqlite3.Connection) -> list[CellSpec]:
    specs = [cell_spec_from_env(c) for c in ACCOUNTS]
    created = store.seed_cells(conn, specs)
    if created:
        logger.info("seeded %d bet cells: %s", len(created), ", ".join(created))
    return specs


def _now_utc() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)


def resolve_open_bet(conn: sqlite3.Connection, spec: CellSpec,
                     row: sqlite3.Row, m5: pd.DataFrame,
                     feed: TickFeed) -> bool:
    """Advance one cell's open bet toward resolution. True when resolved.

    Ticks first (ordered → unambiguous); bar-conservative walk as fallback
    when the tick fetch fails or the feed is in a halt (no ticks at all).
    """
    resolver = store.build_resolver(row, spec.spread_cost_per_oz)
    bet = resolver.bet
    entry_epoch = int(bet.entry_ts.replace(tzinfo=timezone.utc).timestamp())
    # resume cursor: last processed tick (ms) or entry time, minus overlap
    from_ms = resolver.last_tick_msc or ((entry_epoch - 5) * 1000)
    from_epoch = max(entry_epoch - 5, from_ms // 1000 - 1)

    ticks = feed.ticks_since(from_epoch)
    if ticks:
        for tick in ticks:
            ts = datetime.fromtimestamp(
                float(tick["time"]), tz=timezone.utc,
            ).replace(tzinfo=None)
            mid = (float(tick["bid"]) + float(tick["ask"])) / 2.0
            msc = tick["time_msc"]  # local dict — .get() was blocked server-side
            state = resolver.step_tick(
                ts, mid, int(msc) if msc else None,
            )
            if state.outcome is not None:
                break
        if resolver.state.outcome is not None:
            store.resolve_bet_row(conn, row, resolver.state)
            outcome = resolver.state.outcome
            logger.info(
                "[%s] bet #%d resolved by TICKS: %s pnl=%.2f bars~%d",
                spec.cell_id, row["id"], outcome,
                resolver.state.pnl or 0.0, resolver.state.bars_to_finish,
            )
            return True
        store.save_progress(conn, row["id"], resolver)
        return False

    if ticks is None:
        # tick source unavailable — bar-conservative fallback. Skip the
        # bars already stepped in earlier cycles (bars_to_finish persists
        # the bar-step count) so a restart never double-counts.
        bars = m5.loc[m5.index > pd.Timestamp(bet.entry_ts)] if m5 is not None else None
        if bars is None or bars.empty:
            return False
        bars = bars.iloc[max(0, resolver.state.bars_to_finish):]
        for ts, bar in bars.iterrows():
            state = resolver.step_bar(
                ts.to_pydatetime(), float(bar["high"]), float(bar["low"]),
            )
            if state.outcome is not None:
                break
        if resolver.state.outcome is not None:
            store.resolve_bet_row(conn, row, resolver.state)
            logger.info(
                "[%s] bet #%d resolved by BARS: %s pnl=%.2f bars=%d%s",
                spec.cell_id, row["id"], resolver.state.outcome,
                resolver.state.pnl or 0.0, resolver.state.bars_to_finish,
                " (ambiguous)" if resolver.state.ambiguous else "",
            )
            return True
        store.save_progress(conn, row["id"], resolver)
    return False


def try_open_bet(conn: sqlite3.Connection, spec: CellSpec, m5: pd.DataFrame,
                 feed: TickFeed, last_signal_bar: dict) -> None:
    """Open a bet when the cell is flat and the last closed bar signals."""
    if m5 is None or len(m5) < entries.MIN_HISTORY_BARS:
        return
    # stale-feed guard (farm parity): entries blocked while the feed is
    # frozen; resolution above still ran on ticks.
    age = (_now_utc() - m5.index[-1].to_pydatetime()).total_seconds()
    if age > MAX_CANDLE_AGE:
        logger.info("[%s] feed stale (%.0fs) — no new entries", spec.cell_id, age)
        return

    signal = entries.signal_on_last_bar(
        m5, spec.family, boll_threshold=spec.boll_threshold,
    )
    if signal is None:
        return
    last_bar_ts = m5.index[-1]
    if last_signal_bar.get(spec.cell_id) == last_bar_ts:
        return  # already acted on this closed bar (no double entry)

    mid = feed.mid()
    if mid is None:
        mid = float(m5["close"].iloc[-1])  # fallback: last closed bar close
    now = _now_utc()

    bet = open_bet(
        cell_id=spec.cell_id,
        direction=signal,
        signal_ts=last_bar_ts.to_pydatetime(),
        entry_ts=now,
        entry_price=mid,
        geometry=spec.geometry,
        risk_amount=store.cell_balance(conn, spec.cell_id) * spec.risk_fraction,
        spread_cost_per_oz=spec.spread_cost_per_oz,
    )
    bet_id = store.insert_bet(conn, bet)
    last_signal_bar[spec.cell_id] = last_bar_ts
    logger.info(
        "[%s] BET #%d OPEN %s @ %.2f | TP %.2f SL %.2f | risk $%.2f qty %.3f oz",
        spec.cell_id, bet_id, bet.direction, bet.entry_price,
        bet.tp_price, bet.sl_price, bet.risk_amount, bet.qty_oz,
    )


def run_cycle(conn: sqlite3.Connection, specs: list[CellSpec], feed: TickFeed,
              last_signal_bar: dict) -> None:
    m5 = load_m5()
    for spec in specs:
        try:
            row = store.get_open_bet(conn, spec.cell_id)
            if row is not None:
                resolve_open_bet(conn, spec, row, m5, feed)
            if store.get_open_bet(conn, spec.cell_id) is None:
                try_open_bet(conn, spec, m5, feed, last_signal_bar)
        except Exception:
            logger.exception("[%s] cycle failed — continuing", spec.cell_id)


def main() -> None:
    if not ACCOUNTS:
        logger.error("ACCOUNTS is empty — nothing to run")
        sys.exit(1)
    conn = store.connect(DB_PATH)
    specs = seed_all_cells(conn)
    logger.info(
        "bet engine starting — %d cells, db=%s, feed=%s, poll=%ds",
        len(specs), DB_PATH, FEED_DIR, POLL_INTERVAL,
    )
    _install_graceful_close(conn)
    feed = TickFeed()
    last_signal_bar: dict = {}
    while True:
        started = time.monotonic()
        try:
            run_cycle(conn, specs, feed, last_signal_bar)
        except Exception:
            logger.exception("cycle crashed — continuing with next cycle")
        elapsed = time.monotonic() - started
        time.sleep(max(1.0, POLL_INTERVAL - elapsed))


def _install_graceful_close(conn: sqlite3.Connection) -> None:
    """Fold the WAL into the main db file on SIGTERM/SIGINT.

    Live incident 2026-11-11 15:20-15:33 UTC: three committed bets lived in
    the -wal file on the container's virtiofs bind mount; when `docker
    compose up -d --build` recreated the container, the WAL was gone by the
    time the new process opened the db (the main file kept the older rows).
    A clean conn.close() makes SQLite checkpoint every committed frame into
    the main file, so a redeploy never depends on WAL survival on the
    container filesystem. Committed inserts are durable through SIGKILL
    (proved by repro, native and docker) — this closes the remaining window
    where a stop/recreate race could orphan the WAL.
    """
    import signal

    def _close_and_exit(signum: int, _frame: object) -> None:
        logger.info("signal %d received — checkpointing bet db, exiting", signum)
        try:
            conn.close()  # SQLite: final WAL checkpoint + remove -wal/-shm
        except Exception:
            logger.exception("graceful close failed — exiting anyway")
        sys.exit(0)

    signal.signal(signal.SIGTERM, _close_and_exit)
    signal.signal(signal.SIGINT, _close_and_exit)


if __name__ == "__main__":
    main()
